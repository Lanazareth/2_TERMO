-- SEM TRANSAÇÃO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSAÇÃO: PODE CONFIRMAR TUDO OU DEESFAZER TUDO

-- ESTRUTURA
START TRANSACTION
    --COMANDOS SQL
    -- INSERT, UPDATE, SELECT
    COMMIT; --CONFIRMA TODAS AS ALTERAÇÕES
    ROLLBACK, --DESFAZ TODAS AS ALTERAÇÕES

-- EX 2: COMMIT - CONFIRMADO ALTERAÇÕES REALIZADAS
START TRANSACTION;
SELECT * FROM produto WHERE ID_PRODUTO =15;
UPDATE produto
SET PRECO = 9.00
WHERE ID_PRODUTO =1;
SELECT * FROM produto WHERE ID_PRODUTO =15;
COMMIT;

-- EX 3: ROLLBACK - DESFAZENDO ALTERAÇÕES AINDA NÃO CONFIRMADAS
START TRANSACTION;
SELECT * FROM PRODUTO WHERE ID_PRODUTO = 1;
UPDATE PRODUTO
SET PRECO = 500.00
WHERE ID_PRODUTO = 1;
SELECT * FROM PRODUTO WHERE ID_PRODUTO = 1;  -- SEMPRE CONSULTAR ANTES E FAZER UPDATE PARA VERIFICAR SE ESTÁ TUDO CERTO
ROLLBACK; -- DESFAZ TODAS AS ALTERAÇÕES NÃO CONFIRMADAS

-- EX 4: SAVEPOINT - CRIAR UM PONTO DE SALVAMENTO OU CHECKPOINT DE UMA TRANSAÇÃO
START TRANSACTION;
UPDATE PRODUTO
SET PRECO = PRECO * 1.50 -- AUMENTANDO 50% NO PREÇO
WHERE ID_CATEGORIA = 1;
SAVEPOINT REAJUSTE_CAFES;
SELECT * from produto where ID_PRODUTO = 1;
UPDATE PRODUTO
SET PRECO = PRECO * 1.50 -- AUMENTANDO 50% NO PREÇO
WHERE ID_CATEGORIA = 1; 
ROLLBACK TO SAVEPOINT REAJUSTE_CAFES; -- DESFAZ APENAS A ALTERAÇÃO FEITA APÓS O SAVEPOINT
COMMIT; -- CONFIRMA TODAS AS ALTERAÇÕES FEITAS ANTES DO SAVEPOINT

-- ex 5: relese savepoint - remover o save point criado anteriormemnte
RELEASE SAVEPOINT  REAJUSTE_CAFES;