-- EX 25: TOTAL COMPRADO POR CLIENTE 
SELECT C.NOME AS CLIENTE, COUNT(P.PEDIDO) AS QTDE_PEDIDOS, SUM(P.VALOR_TOTAL) AS TOTAL_COMPRADO
FROM CLIENTE AS C 
INNER JOIN PEDIDO A P 
ON P.ID_CLIENTE = C.ID_CLIENTE
WHERE P.STATUS_PEDIDO = 'PENDENTE' 
GROUP BY C.ID_CLIENTE, C.NOME
ORDER BY TOTAL_COMPRADO DESC;

--  RELATORIO COMPLETO DO PEDIDO
-- EX 26 COMBINAÇÃO DE VARIAVEIS TABELA PARA UMA CONSULTA COMPLETA
SELECT P.ID_PEDIDO, DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H:%i') AS DATA, C.NOME AS CLIENTE, PR.NOME_PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO, IP.QUANTIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN CLIENTE AS C 
ON C.ID_CLIENTE = P.ID_CLIENTE 
INNER JOIN item_pedido AS IP 
ON IP.ID_PEDIDO = P.ID_PEDIDO 
INNER JOIN produto AS PR 
ON PR.ID_PRODUTO = IP.ID_PRODUTO 
ORDER BY P.ID_PEDIDO, PR.NOME_PRODUTO;

